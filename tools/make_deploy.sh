#!/bin/sh
# Put the hostable browser build (no game inside) on the `deploy` branch, ready
# for a static host such as Render (render.yaml) or Cloudflare Pages (_headers).
#
#   tools/make_deploy.sh [--push]
#
# The branch holds only: site/ (page, runtime, in-browser recompiler), the
# config writer and render.yaml. config.json is written at deploy time from
# PICK_FILES / GAME_ZIP (tools/web_config.py); render.yaml sets PICK_FILES=true.
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"
tools/build.sh --web-host >/dev/null

WT="$ROOT/build/deploy-worktree"
git worktree remove --force "$WT" 2>/dev/null || true
if git show-ref --quiet refs/heads/deploy; then
  git worktree add -q "$WT" deploy
else
  git worktree add -q --detach "$WT"
  (cd "$WT" && git checkout -q --orphan deploy && git rm -rq --cached . && git clean -fdxq)
fi

# what goes online: nothing from the game
rm -rf "$WT/site" "$WT/tools"
mkdir -p "$WT/site" "$WT/tools"
for f in tkdr.html tkdr.js tkdr.wasm disc.mjs _headers; do cp "build/web-host/$f" "$WT/site/"; done
cp build/web-host/tkdr.html "$WT/site/index.html"
cp -R build/web-host/recomp "$WT/site/recomp"
cp tools/web_config.py "$WT/tools/"
cat > "$WT/render.yaml" <<'EOF'
# Render static site: the hostable build (players bring their own files)
services:
  - type: web
    name: tkdr
    runtime: static
    buildCommand: python3 tools/web_config.py site
    staticPublishPath: ./site
    envVars:
      - key: PICK_FILES
        value: "true"
    headers:
      - path: /*
        name: Cross-Origin-Opener-Policy
        value: same-origin
      - path: /*
        name: Cross-Origin-Embedder-Policy
        value: require-corp
EOF
cat > "$WT/README.md" <<'EOF'
# tkdr-recomp: hostable browser build

Generated by `tools/make_deploy.sh` on the main branch. Contains no game data:
the page, the runtime (WebAssembly) and the in-browser recompiler. Players bring
their own dump; it is translated and kept in their own browser.
EOF

# refuse anything that looks like game data
if find "$WT/site" -type f \( -iname '*.iso' -o -iname '*.cso' -o -iname '*.zip' -o -iname '*.bin' -o -iname '*.elf' -o -iname '*.data' \) | grep -q .; then
  echo "error: game-like files in the deploy tree" >&2
  exit 1
fi

cd "$WT"
git add -A
if git diff --cached --quiet; then
  echo "deploy branch already up to date"
else
  git -c user.name=gasparegas -c user.email=57927360+gasparegas@users.noreply.github.com commit -qm "Hostable build from $(git -C "$ROOT" rev-parse --short HEAD)"
  echo "deploy branch: $(git log --oneline -1)"
fi
[ "$1" = "--push" ] && git push -q -u origin deploy && echo "pushed to origin/deploy"
du -sh site
