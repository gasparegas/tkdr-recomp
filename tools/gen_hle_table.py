#!/usr/bin/env python3
"""Regenerate runtime/hle/hle_table.c from the HLE functions defined in runtime/hle/*.c."""
import glob
import os
import re

root = os.path.join(os.path.dirname(__file__), "..", "runtime", "hle")
pat = re.compile(r"^void (_*sce\w+)\(Ctx \*c\)\s*\{", re.M)
names = sorted({m.group(1) for f in glob.glob(os.path.join(root, "*.c"))
                for m in pat.finditer(open(f).read())})
with open(os.path.join(root, "hle_table.c"), "w") as out:
    out.write("// Generated by tools/gen_hle_table.py - do not edit.\n#include \"hle.h\"\n\n")
    out.writelines(f"void {n}(Ctx *c);\n" for n in names)
    out.write("\nconst HleEntry g_hle_table[] = {\n")
    out.writelines(f'    {{"{n}", {n}}},\n' for n in names)
    out.write(f"}};\nconst unsigned g_hle_table_count = {len(names)};\n")
print(f"{len(names)} HLE functions")
